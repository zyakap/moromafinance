        mode_of_payment = dbframe.Mode
        
        amount = Decimal(amount)
        
        #split the name first into first name and last name 
        first_name = name.split()[0]
        if len(name.split()) == 3:
            middle_name = name.split()[1]
            last_name = name.split()[2]
        else:
            last_name = name.split()[1]
            middle_name = None
        

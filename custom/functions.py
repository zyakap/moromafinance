def fund_additional_loan(request, running_loan_id, new_loan_id):
    running_loan = Loan.objects.get(id=running_loan_id)
    new_loan = Loan.objects.get(id=new_loan_id)

    today = datetime.date.today()

    # Structure the new loan against the running loan per the configured refinance
    # type (offset / add-on / concurrent): copies history to the new loan, closes
    # the running loan, builds the combined schedule and resets the schedule cursor
    # (fortnights_settled). See loan/refinance.py.
    from loan.refinance import apply_refinance
    loan = apply_refinance(request, running_loan, new_loan, notify=False, today=today)

    user = UserProfile.objects.get(id=loan.owner.id)
    user.number_of_loans += 1
    # A funded loan implies signed terms + credit-check consent.
    user.credit_consent = 'YES'
    user.terms_consent = 'YES'
    user.save()

    repayment_dates_list = loan.get_repayment_dates()

    

    from decimal import Decimal as _D
    try:
        _ls = AdminSettings.objects.get(settings_name='setting1')
        _fee_enabled = getattr(_ls, 'processing_fee', 'NO') == 'YES'
        _fee_mode = getattr(_ls, 'processing_fee_collection_mode', 'CASH')
    except Exception:
        _fee_enabled = False
        _fee_mode = 'CASH'
    _processing_fee = ProcessingFeeTier.get_fee_for_amount(loan.amount) if _fee_enabled else 0
    if _fee_enabled and _processing_fee > 0:
        loan.processing_fee = _processing_fee
    else:
        loan.processing_fee = 0
    loan.save()
    Statement.objects.create(owner=user, ref=f'{loan.ref}ALF', loanref=loan, type="FUNDING", statement="Additional Loan Funded", credit=loan.amount, balance=loan.total_outstanding - (loan.interest or 0), date=today, uid=user.uid, luid=settings.LUID)
    Statement.objects.create(owner=user, ref=f'{loan.ref}ALF', loanref=loan, type="FUNDING", statement="Loan Interest Charged", credit=(loan.interest or 0), balance=loan.total_outstanding, date=today, uid=user.uid, luid=settings.LUID)

    

    #### Update loan balances and everything
    loan.classification = 'ADDITIONAL'
    loan.principal_loan_paid += running_loan.principal_loan_paid
    loan.interest_paid += running_loan.interest_paid
    loan.default_interest_paid += running_loan.default_interest_paid
    loan.total_paid += running_loan.total_paid
    
    loan.fortnights_paid += running_loan.fortnights_paid
    loan.number_of_repayments += running_loan.number_of_repayments
    loan.last_repayment_amount = running_loan.last_repayment_amount
    loan.last_repayment_date = running_loan.last_repayment_date
    loan.number_of_advance_payments += running_loan.number_of_advance_payments
    loan.last_advance_payment_date = running_loan.last_advance_payment_date
    loan.last_advance_payment_amount = running_loan.last_advance_payment_amount
    loan.total_advance_payment += running_loan.total_advance_payment
    loan.advance_payment_surplus += running_loan.advance_payment_surplus
    
    loan.days_in_default += running_loan.days_in_default
    # Arrears, default counters and receivables are already carried forward by
    # apply_refinance (see loan/refinance.py) — do not add them again here.

    loan.opt1 = running_loan.opt1
    loan.opt2 = running_loan.opt2
    loan.opt3 = running_loan.opt3   
    loan.opt4 = running_loan.opt4
    loan.opt5 = running_loan.opt5
    loan.dcc = running_loan.dcc
    loan.notes = running_loan.notes
    loan.save()

    # Construct the repayment dates HTML string
    repayment_dates_html = ''.join([f'<div>{date}</div>' for date in repayment_dates_list])
    #send email to user
    

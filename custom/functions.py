def classify_loan_complete(request):
    # AWAITING_REFUND loans are already at total_outstanding == 0 by design
    # (the debt is settled) but must NOT be blindly swept into COMPLETED here —
    # that would silently erase the "still owe this client a refund" flag and
    # hide it from the loans list. They stay open until refunded/attributed
    # via the Client Credits workflow (loan/functions.close_loan_with_credit).
    loans = (Loan.objects.filter(funded_category__isnull=False)
             .exclude(funded_category='AWAITING_REFUND').order_by('id'))
    count_of_update = 0
    for loan in loans:
        if loan.total_outstanding == 0:
            loan.funded_category = 'COMPLETED'
            loan.status = 'COMPLETED'
            loan.save()
            count_of_update += 1
    messages.success(request, f'{count_of_update} loans have been classified as completed')
    return redirect('admin_dashboard')
    

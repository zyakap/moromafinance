#loanmasta_combination_check
def combination_check(amount, num_fns):
    """Return 0 when amount/term is a valid combination, else the max term allowed.

    Validates against the terms actually published in REPAYMENT_TABLE rather than
    a numeric range, because the minimum term depends on the loan amount
    (14 fortnights below K1000, 9 below K2000, otherwise 7).
    """
    terms = REPAYMENT_TABLE.get(amount)
    if terms is None:
        return 0

    try:
        min_fn = int(get_loan_config()['min_fn'])
    except Exception:
        min_fn = min(terms)

    if num_fns in terms and num_fns >= min_fn:
        return 0
    return max(terms)


#moroma_repayment
def repayment(amount, interest_type, fns):
    """Fortnightly repayment for a loan, read from the MOROMA repayment schedule.

    Args:
        amount (float): loan amount (must be a K50 step from 500 to 5000)
        interest_type (str): retained for signature compatibility; the published
            schedule already has the interest baked into each cell.
        fns (int): number of fortnights

    Returns:
        float: the fortnightly repayment, or an error string when the
        amount/term is not in the published schedule.
    """
    terms = REPAYMENT_TABLE.get(amount)
    if terms is None:
        return "Invalid loan amount"

    pmt = terms.get(fns)
    if pmt is None:
        return "Invalid number of fortnights"

    return pmt

